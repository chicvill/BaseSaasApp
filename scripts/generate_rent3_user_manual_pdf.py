def build_pdf(output_path: str) -> None:
    reg_font, bold_font = register_korean_fonts()
    doc = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        leftMargin=15 * mm,
        rightMargin=15 * mm,
        topMargin=17 * mm,
        bottomMargin=16 * mm,
        title="Rent3 초보자용 통합 사용자 매뉴얼",
        author="BaseSaasApp · Smart Rent3",
    )
    usable_w = A4[0] - 30 * mm
    st = build_styles(reg_font, bold_font)
    story: List[Any] = []

    add_cover_page(story, st, usable_w)
    add_toc_page(story, st, usable_w)
    add_overview_page(story, st, usable_w)
    for feat in FEATURES:
        add_feature_page(story, feat, st, usable_w)
    add_appendix_page(story, st, usable_w)

    doc.build(story, onFirstPage=draw_page_chrome, onLaterPages=draw_page_chrome)


